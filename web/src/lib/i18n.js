  const STORAGE_KEY = 'fashtry_locale';

  function getLocale() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
    const lang = navigator.language || navigator.userLanguage || '';
    return lang.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  function setLocale(locale) {
    if (locale !== 'zh' && locale !== 'en') return;
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
    applyI18n(document);
    updatePageTitle();
    updateLangSwitchActive();
    window.dispatchEvent(new CustomEvent('localechange', { detail: { locale } }));
    if (typeof window.onLocaleChange === 'function') {
      window.onLocaleChange(locale);
    }
    return locale;
  }

  function updatePageTitle() {
    applySeoFromPath(location.pathname || '/');
  }

  function t(key, params) {
    const locale = getLocale();
    const dict = messages[locale] || messages.zh;
    let str = dict[key] ?? messages.zh[key] ?? key;
    if (params && typeof params === 'object') {
      Object.keys(params).forEach((k) => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
      });
    }
    return str;
  }

  function formatCredits(n, locale) {
    const loc = locale || getLocale();
    const suffix = loc === 'en' ? ' credits' : ' 点数';
    return (n ?? 0) + suffix;
  }

  function formatApiError(msg) {
    if (!msg || typeof msg !== 'string') return t('errRequestFail');
    const key = MSG_TO_KEY[msg.trim()];
    return key ? t(key) : msg;
  }

  function formatAmount(amount, currency) {
    if (amount == null) return '';
    const n = Number(amount);
    if (currency === 'USD') {
      return '$' + n.toFixed(2);
    }
    return '¥' + n.toFixed(2);
  }

  function applyI18n(root) {
    const el = root || document;
    el.querySelectorAll('[data-i18n]').forEach((node) => {
      const key = node.getAttribute('data-i18n');
      if (!key) return;
      const params = {};
      for (const a of node.attributes) {
        if (a.name.startsWith('data-i18n-') && a.name !== 'data-i18n') {
          const k = a.name.replace('data-i18n-', '');
          params[k] = a.value;
        }
      }
      const text = t(key, Object.keys(params).length ? params : undefined);
      if (node.getAttribute('data-i18n-html') === '1') {
        node.innerHTML = text;
      } else {
        node.textContent = text;
      }
    });
  }

  function updateLangSwitchActive() {
    const loc = getLocale();
    document.querySelectorAll('.lang-dropdown-option[data-lang]').forEach((el) => {
      el.classList.toggle('active', el.dataset.lang === loc);
    });
  }

  function initLangSwitch() {
    updateLangSwitchActive();
  }

  function initI18n() {
    document.documentElement.lang = getLocale() === 'zh' ? 'zh-CN' : 'en';
    applyI18n(document);
    updatePageTitle();
    initLangSwitch();
  }

export const i18n = {
    getLocale,
    setLocale,
    updatePageTitle,
    t,
    formatCredits,
    formatAmount,
    formatApiError,
    applyI18n,
    initI18n,
    messages,
  };

export function bootI18n() {
  const boot = () => {
    // 支持 ?lang=en / ?lang=zh 直达指定语言，方便海外分享链接；写入 localStorage 后
    // 语言切换开关仍可正常覆盖（只在首屏引导时读一次 URL）。
    try {
      const lang = new URLSearchParams(location.search).get('lang');
      if ((lang === 'zh' || lang === 'en') && getLocale() !== lang) setLocale(lang);
    } catch (e) {
      /* 非浏览器环境忽略 */
    }
    initI18n();
  };
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
}
